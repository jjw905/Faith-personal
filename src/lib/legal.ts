export function getLegalSections(doc: LegalDoc): LegalSection[] {
  return LEGAL_SECTIONS.filter((s) => s.group === doc);
}

export function getLegalNav(doc: LegalDoc) {
  return getLegalSections(doc).map((s) => ({
    id: s.id,
    title: s.title,
  }));
}

export function searchLegalSections(
  doc: LegalDoc,
  query: string,
): LegalSection[] {
  const sections = getLegalSections(doc);
  const q = query.trim();
  if (!q) return sections;
  return sections.filter((section) => {
    if (docsTextMatches(section.title, q)) return true;
    return section.items.some((item) => docsTextMatches(item, q));
  });
}
