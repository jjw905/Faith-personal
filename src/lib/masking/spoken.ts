/**
 * regex alternation 문자열 생성.
 * 긴 것 우선 정렬 (골뱅 이 > 골뱅).
 */
export function alt(words: readonly string[]): string {
  return [...words]
    .sort((a, b) => b.length - a.length)
    .map((w) => w.replace(/\s+/g, "\\s*"))
    .join("|");
}

