const NOT_NAME = new Set([...TITLES, ...COMMON_NOUNS]);

/**
 * 이름일 수 없는 말끝.
 *
 * 단어를 하나씩 목록에 넣는 방식으로는 끝이 없다. 성씨 71자가 흔한 음절이라
 * '하는데 위원님', '위원들에게'처럼 보통 말이 계속 걸린다.
 * 이름에는 붙지 않는 어미와 복수 표시로 걸러낸다.
 */
const GRAMMAR_ENDINGS = [
  "는데",
  "면서",
  "도록",
  "고자",
  "지만",
  "라고",
  "다고",
  "는",
  "던",
  "들",
  "며",
  "만",
];

/** 이름으로 가리면 안 되는 말인지. */
export function isNotPersonName(value: string): boolean {
  const t = value.trim();
  if (!t) return true;
  if (NOT_NAME.has(t)) return true;
  if (GRAMMAR_ENDINGS.some((end) => t.endsWith(end))) return true;
  // 직함이 뒤에 붙은 형태 (노조위원장, 사무총장)
  return TITLES.some((title) => title.length >= 2 && t.endsWith(title));
}
