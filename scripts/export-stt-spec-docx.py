FONT = "Apple SD Gothic Neo"


def set_kr_font(run, size=11, bold=False):
    run.font.size = Pt(size)
    run.bold = bold
    run.font.name = FONT
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:eastAsia"), FONT)


def h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        set_kr_font(run, size=16 if level == 1 else 13, bold=True)
    return p


def body(doc, text, bold=False, size=11):
    p = doc.add_paragraph()
    set_kr_font(p.add_run(text), size=size, bold=bold)
    return p


def bullets(doc, items):
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        set_kr_font(p.add_run(item), size=11)


def steps(doc, items):
    for item in items:
        p = doc.add_paragraph(style="List Number")
        set_kr_font(p.add_run(item), size=11)


def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for i, name in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.text = ""
        set_kr_font(cell.paragraphs[0].add_run(name), size=10, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = ""
            set_kr_font(cells[i].paragraphs[0].add_run(str(value)), size=10)
    doc.add_paragraph()
    return t


